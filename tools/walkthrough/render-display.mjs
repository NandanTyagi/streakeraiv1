import {bundle} from '@remotion/bundler';
import {selectComposition,renderMedia,renderStill} from '@remotion/renderer';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const executable='C:/Program Files/Google/Chrome/Application/chrome.exe';
const serveUrl=await bundle({entryPoint:path.resolve('index.jsx'),publicDir:path.resolve('public'),outDir:path.resolve('bundle')});
const composition=await selectComposition({serveUrl,id:'StreakerMobile',browserExecutable:executable});
const timeline=JSON.parse(fs.readFileSync('timeline.json'));
const c=timeline.chapters.find(c=>c.id==='display');
for(const p of [.1,.18,.35,.8])await renderStill({serveUrl,composition,browserExecutable:executable,frame:c.start+Math.floor(c.duration*p),output:`public/review-product-${p}.png`});
if(process.argv.includes('--stills'))process.exit(0);
let last=-1;
await renderMedia({serveUrl,composition,browserExecutable:executable,codec:'h264',crf:18,pixelFormat:'yuv420p',muted:true,frameRange:[c.start,c.start+c.duration-1],outputLocation:'public/review-display-v3.mp4',concurrency:2,onProgress:({progress})=>{const n=Math.floor(progress*10);if(n!==last){last=n;console.log(`Display render ${n*10}%`);}}});
const ffmpeg=process.env.FFMPEG || 'C:/Users/nanda/LocalWebDev/Embla/repos/embla-audio-worker/node_modules/ffmpeg-static/ffmpeg.exe';
const source='../../public/videos/streaker-mobile-walkthrough.mp4';
const output='public/review-walkthrough-v3.mp4';
const filter=`[0:v]trim=end_frame=${c.start},setpts=PTS-STARTPTS[a];[1:v]setpts=PTS-STARTPTS[b];[0:v]trim=start_frame=${c.start+c.duration},setpts=PTS-STARTPTS[d];[a][b][d]concat=n=3:v=1:a=0[v]`;
const result=spawnSync(ffmpeg,['-v','error','-y','-i',source,'-i','public/review-display-v3.mp4','-filter_complex',filter,'-map','[v]','-map','0:a','-c:v','libx264','-preset','fast','-crf','20','-pix_fmt','yuv420p','-c:a','copy','-movflags','+faststart',output],{stdio:'inherit'});
if(result.status!==0)throw Error('Assembly failed');
const check=spawnSync(ffmpeg,['-v','error','-i',output,'-f','null','-'],{stdio:'inherit'});
if(check.status!==0)throw Error('Decode failed');
console.log('Ready for review: '+output);
